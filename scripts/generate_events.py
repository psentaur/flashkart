#!/usr/bin/env python3
"""Generate typed event payloads directly from the reviewed draft schema."""
import json, subprocess, sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
schema=json.loads((ROOT/'contracts/events.schema.json').read_text())

def typename(s):
    return ''.join(x.upper() if x in ('id','ids','ms','json') else x.title() for x in s.split('_'))

def typ(s):
    t=s.get('type','string')
    if t=='object':
        props=s.get('properties')
        if props:
            return 'struct { '+ '; '.join(field(k,v,k in s.get('required',[])) for k,v in props.items())+' }'
        vals=next(iter(s.get('patternProperties',{}).values()),s.get('additionalProperties',{}))
        return 'map[string]'+(typ(vals) if isinstance(vals,dict) else 'any')
    if t=='array':return '[]'+typ(s['items'])
    return {'integer':'int64','number':'float64','boolean':'bool'}.get(t,'string')

def field(k,v,required):
    ty=typ(v)
    if not required:ty='*'+ty
    return typename(k)+' '+ty+' `json:"'+k+('"`' if required else ',omitempty"`')

out='// Code generated by scripts/generate_events.py; DO NOT EDIT.\n\n// Package events contains typed payloads for the reviewed event contract.\npackage events\n\n'
for variant in schema['oneOf']:
    p=variant['properties'];data=p['data'];name=p['type']['const']
    out+='type '+name+' struct {\n'+'\n'.join(field(k,v,k in data['required']) for k,v in data['properties'].items())+'\n}\n\n'
raw=subprocess.run(['gofmt'],input=out.encode(),stdout=subprocess.PIPE,check=True).stdout
path=ROOT/'internal/platform/events/payloads.gen.go'
if '--check' in sys.argv:
    if not path.exists() or path.read_bytes()!=raw:raise SystemExit('Event binding drift')
else:path.write_bytes(raw)
